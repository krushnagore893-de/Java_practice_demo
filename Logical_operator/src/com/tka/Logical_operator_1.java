package com.tka;

public class Logical_operator_1 {
	public static void main(String[] args) {
		
		int i = 67;
		i++;
		i--;
		--i;
		System.out.println(i++);
		--i;
		i++;
		System.out.println(--i);
		i++;
		--i;
		System.out.println(i+5);
		--i;
		i++;
		System.out.println(i+2);
		++i;
		--i;
		System.out.println(i++);
		--i;
		i++;
		System.out.println(i);
	}
}
