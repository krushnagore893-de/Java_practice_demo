
public class BankAccound {
	public static void main (String[]args) {
		byte age = 19;
		short branchCode = 5227;
		int accountNumber = 234567611;
		long mobileNumber = 23456789032l;
		float interrate = 7.5f;
		double salary = 67873.90;
		char accountType = 's';
		boolean active = true;
		
		System.out.println("age -->"+age);
		System.out.println("branchCode --->"+branchCode);
		System.out.println("accountNumber --->"+accountNumber);
		System.out.println("mobileNumber ---->"+mobileNumber);
		System.out.println("interrate ---->"+interrate);
		System.out.println("salary --->"+salary);
		System.out.print("accountType --->"+accountType);
		System.out.println("active --->"+active);
	}
}
